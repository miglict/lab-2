import math


def calculate_y(x):
    """
    Вычисляет y по графику функции.
    """
    # Участок 1: от -4 до -2 (включительно)
    if -4 <= x <= -2:
        # Прямая через (-4, -1) и (-2, 1) -> y = x + 3
        y = x + 3

    # Участок 2: от -2 до 4 (включительно)
    elif -2 < x <= 4:
        # Прямая через (-2, 1) и (4, -2) -> y = -0.5 * x
        y = -0.5 * x

    # Участок 3: от 4 до 6 (включительно)
    elif 4 < x <= 6:
        # Горизонтальная линия
        y = -2.0

    # Участок 4: от 6 до 10 (включительно)
    elif 6 < x <= 10:
        # Полуокружность с центром (8, -2) и радиусом 2
        # y = -2 + sqrt(R^2 - (x - x_center)^2)
        y = -2 + math.sqrt(4 - (x - 8) ** 2)

    else:
        # Если x вне диапазона [-4, 10]
        return None

    return y


def main():
    try:
        print("Программа вычисления значения функции по графику")
        x = float(input("Введите значение x (от -4 до 10): "))

        result = calculate_y(x)

        if result is not None:
            print(f"При x = {x}, значение y = {result:.4f}")
        else:
            print("Ошибка: x выходит за пределы области определения функции [-4, 10].")

    except ValueError:
        print("Ошибка ввода: пожалуйста, введите число.")


if __name__ == "__main__":
    main()